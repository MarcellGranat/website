// Reads posts/*/index.qmd front matter and writes data/posts.js (ES module).
// Usage: node modern/scripts/build-posts.mjs   (run from the repo root)
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const postsDir = join(here, '..', '..', 'posts');
const out = join(here, '..', 'data', 'posts.js');

const unquote = (s) => s.trim().replace(/^(['"])(.*)\1$/, '$2').replace(/\s+/g, ' ');

function parseFrontMatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!m) return {};
  const data = {};
  let list = null;
  for (const line of m[1].split(/\r?\n/)) {
    const item = line.match(/^\s+-\s+(.*)$/);
    if (item && list) { list.push(unquote(item[1])); continue; }
    const kv = line.match(/^([A-Za-z_-]+):\s*(.*)$/);
    if (!kv) continue;
    if (kv[2].trim() === '' || kv[2].trim() === '|') { list = data[kv[1]] = []; }
    else { data[kv[1]] = unquote(kv[2]); list = null; }
  }
  return data;
}

const posts = readdirSync(postsDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(postsDir, d.name, 'index.qmd')))
  .map((d) => {
    const fm = parseFrontMatter(readFileSync(join(postsDir, d.name, 'index.qmd'), 'utf8'));
    return {
      id: d.name,
      title: fm.title ?? d.name,
      date: fm.date ?? '',
      tags: [...(Array.isArray(fm.categories) ? fm.categories : []), ...(Array.isArray(fm.tags) ? fm.tags : [])],
      image: fm.image && existsSync(join(postsDir, d.name, fm.image)) ? fm.image : null,
    };
  })
  .sort((a, b) => b.date.localeCompare(a.date));

writeFileSync(out, `// Generated by scripts/build-posts.mjs - do not edit by hand.\nexport const POSTS = ${JSON.stringify(posts, null, 2)};\n`);
console.log(`Wrote ${posts.length} posts to ${out}`);
